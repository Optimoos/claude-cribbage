//go:build ignore

// h2stats_gen plays heuristic self-play games and writes h2stats.go: the
// per-hand score distributions that heuristic2's win table and endgame
// discards are built from. Run it with go generate.
package main

import (
	"bytes"
	"context"
	"fmt"
	"go/format"
	"log"
	"os"
	"runtime"
	"slices"

	"cribbage/internal/bots"
	"cribbage/internal/engine"
	"cribbage/internal/expert"
)

const (
	games  = 200000
	seed   = 17
	shrink = 200
)

const numShapes = 1820

// shapeIndex and forEachShape mirror bots.shapeIndex: shapes are numbered
// in the order forEachShape visits them.
var shapeIdx = func() []int16 {
	idx := make([]int16, 14*14*14*14)
	forEachShape(func(sh int, r [4]int) { idx[((r[0]*14+r[1])*14+r[2])*14+r[3]] = int16(sh) })
	return idx
}()

func shapeIndex(kept [4]engine.Card) int {
	r := [4]int{kept[0].Rank(), kept[1].Rank(), kept[2].Rank(), kept[3].Rank()}
	slices.Sort(r[:])
	return int(shapeIdx[((r[0]*14+r[1])*14+r[2])*14+r[3]])
}

func forEachShape(f func(sh int, ranks [4]int)) {
	n := 0
	for a := 1; a <= 13; a++ {
		for b := a; b <= 13; b++ {
			for c := b; c <= 13; c++ {
				for d := c; d <= 13; d++ {
					f(n, [4]int{a, b, c, d})
					n++
				}
			}
		}
	}
}

func main() {
	sp, err := expert.Collect(context.Background(),
		func(int) bots.Bot { return bots.NewHeuristic() }, games, runtime.NumCPU(), seed)
	if err != nil {
		log.Fatal(err)
	}
	var peg [32][32]float64
	var show [2][13][30]float64
	var dealer [64]float64
	var rankN [13]float64
	var kept [2][13]float64
	var throws [2][13][13]float64
	var shapeSum, shapeN [2][numShapes]float64
	var rankSum, rankN2 [2][13]float64
	var diffSum [2]float64
	for _, h := range sp.Details {
		peg[min(h.Peg[0], 31)][min(h.Peg[1], 31)]++
		r := h.Starter.Rank() - 1
		rankN[r]++
		show[0][r][h.Show[0]]++
		show[1][r][h.Show[1]]++
		t := int(h.Show[0]) + int(h.Crib)
		if r == 10 {
			t += 2 // his heels
		}
		dealer[min(t, 63)]++
		for side := range h.Kept {
			for _, c := range h.Kept[side] {
				kept[side][c.Rank()-1]++
			}
			diff := float64(h.Peg[side]) - float64(h.Peg[1-side])
			diffSum[side] += diff
			sh := shapeIndex(h.Kept[side])
			shapeSum[side][sh] += diff
			shapeN[side][sh]++
			for _, c := range h.Kept[side] {
				rankSum[side][c.Rank()-1] += diff
				rankN2[side][c.Rank()-1]++
			}
			r1, r2 := h.Discards[side][0].Rank()-1, h.Discards[side][1].Rank()-1
			throws[side][min(r1, r2)][max(r1, r2)]++
		}
	}
	n := float64(len(sp.Details))

	// Pegging by shape: the mean of my pegging less theirs, shrunk toward
	// the side's mean plus each kept rank's own effect.
	var pegShape [2][numShapes]float64
	for side := range pegShape {
		base := diffSum[side] / n
		forEachShape(func(sh int, ranks [4]int) {
			prior := base
			for _, r := range ranks {
				prior += rankSum[side][r-1]/rankN2[side][r-1] - base
			}
			pegShape[side][sh] = (shapeSum[side][sh] + shrink*prior) / (shapeN[side][sh] + shrink)
		})
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by h2stats_gen.go from %d heuristic self-play games (%d hands, seed %d). DO NOT EDIT.\n\n", games, len(sp.Details), seed)
	b.WriteString("package bots\n\n")
	b.WriteString("// h2Peg[d][p] is the probability that the dealer pegs d points and the pone p in a hand (31 means 31 or more).\n")
	b.WriteString("var h2Peg = [32][32]float32{\n")
	for d := range peg {
		writeRow(&b, peg[d][:], n)
	}
	b.WriteString("}\n\n")
	b.WriteString("// h2Show[side][r-1][k] is the probability that a hand shows k points given a starter of rank r; side 0 is the dealer, 1 the pone.\n")
	b.WriteString("var h2Show = [2][13][30]float32{\n")
	for s := range show {
		b.WriteString("{\n")
		for r := range show[s] {
			writeRow(&b, show[s][r][:], rankN[r])
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("// h2Dealer[k] is the probability that the dealer's show, crib and heels together score k points (63 means 63 or more).\n")
	b.WriteString("var h2Dealer = [64]float32")
	writeRow(&b, dealer[:], n)
	b.Truncate(b.Len() - 2) // the row's ",\n"
	b.WriteString("\n\n// h2Keep[side][r-1] is how much likelier a card of rank r is to be kept than a random card; side 0 is the dealer, 1 the pone.\n")
	b.WriteString("var h2Keep = [2][13]float32{\n")
	for side := range kept {
		writeRow(&b, kept[side][:], 4*n/13)
	}
	b.WriteString("}\n\n")
	b.WriteString("// h2Throw[side][r1-1][r2-1], r1 <= r2, is the probability that a side throws ranks r1 and r2 to the crib; side 0 is the dealer, 1 the pone.\n")
	b.WriteString("var h2Throw = [2][13][13]float32{\n")
	for side := range throws {
		b.WriteString("{\n")
		for r := range throws[side] {
			writeRow(&b, throws[side][r][:], n)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "// h2PegShape[side][shape] is the mean of a side's pegging less the other side's when it keeps four cards of that shape (shapeIndex), shrunk toward a per-rank estimate with the weight of %d hands; side 0 is the dealer, 1 the pone.\n", shrink)
	b.WriteString("var h2PegShape = [2][numShapes]float32{\n")
	for side := range pegShape {
		writeRow(&b, pegShape[side][:], 1)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("h2stats.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func writeRow(b *bytes.Buffer, row []float64, n float64) {
	b.WriteString("{")
	for i, x := range row {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%.6g", x/n)
	}
	b.WriteString("},\n")
}
