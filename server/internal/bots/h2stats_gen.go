//go:build ignore

// h2stats_gen plays heuristic self-play games and writes h2stats.go: the
// per-hand score distributions that heuristic2's win table and endgame
// discards are built from. Run it with go generate.
package main

import (
	"bytes"
	"context"
	"fmt"
	"go/format"
	"log"
	"os"
	"runtime"

	"cribbage/internal/bots"
	"cribbage/internal/expert"
)

const (
	games = 200000
	seed  = 17
)

func main() {
	sp, err := expert.Collect(context.Background(),
		func(int) bots.Bot { return bots.NewHeuristic() }, games, runtime.NumCPU(), seed)
	if err != nil {
		log.Fatal(err)
	}
	var peg [32][32]float64
	var show [2][13][30]float64
	var dealer [64]float64
	var rankN [13]float64
	for _, h := range sp.Details {
		peg[min(h.Peg[0], 31)][min(h.Peg[1], 31)]++
		r := h.Starter.Rank() - 1
		rankN[r]++
		show[0][r][h.Show[0]]++
		show[1][r][h.Show[1]]++
		t := int(h.Show[0]) + int(h.Crib)
		if r == 10 {
			t += 2 // his heels
		}
		dealer[min(t, 63)]++
	}
	n := float64(len(sp.Details))

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by h2stats_gen.go from %d heuristic self-play games (%d hands, seed %d). DO NOT EDIT.\n\n", games, len(sp.Details), seed)
	b.WriteString("package bots\n\n")
	b.WriteString("// h2Peg[d][p] is the probability that the dealer pegs d points and the pone p in a hand (31 means 31 or more).\n")
	b.WriteString("var h2Peg = [32][32]float32{\n")
	for d := range peg {
		writeRow(&b, peg[d][:], n)
	}
	b.WriteString("}\n\n")
	b.WriteString("// h2Show[side][r-1][k] is the probability that a hand shows k points given a starter of rank r; side 0 is the dealer, 1 the pone.\n")
	b.WriteString("var h2Show = [2][13][30]float32{\n")
	for s := range show {
		b.WriteString("{\n")
		for r := range show[s] {
			writeRow(&b, show[s][r][:], rankN[r])
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("// h2Dealer[k] is the probability that the dealer's show, crib and heels together score k points (63 means 63 or more).\n")
	b.WriteString("var h2Dealer = [64]float32")
	writeRow(&b, dealer[:], n)
	src := bytes.TrimSuffix(b.Bytes(), []byte(",\n"))
	src, err = format.Source(append(src, '\n'))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("h2stats.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func writeRow(b *bytes.Buffer, row []float64, n float64) {
	b.WriteString("{")
	for i, x := range row {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%.6g", x/n)
	}
	b.WriteString("},\n")
}
